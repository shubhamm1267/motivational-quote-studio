export function getSeed(category='all',lastId='') {
 const choices=FACTS.filter(f=>(category==='all'||f.category===category)&&f.id!==lastId);
 const pool=choices.length?choices:FACTS.filter(f=>category==='all'||f.category===category);
 if(!pool.length)throw Error('Category contains no quote seeds.');
 return pool[Math.floor(Math.random()*pool.length)];
}

